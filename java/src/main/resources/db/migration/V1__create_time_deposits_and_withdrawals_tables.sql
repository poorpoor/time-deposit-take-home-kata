CREATE TABLE "timeDeposits" (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "planType"  VARCHAR(255)   NOT NULL,
    days        INTEGER        NOT NULL,
    balance     NUMERIC(19, 2) NOT NULL
);

CREATE TABLE withdrawals (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "timeDepositId" INTEGER        NOT NULL REFERENCES "timeDeposits"(id) ON DELETE CASCADE,
    amount          NUMERIC(19, 2) NOT NULL,
    date            DATE           NOT NULL
);

CREATE INDEX idx_withdrawals_time_deposit_id ON withdrawals ("timeDepositId");
